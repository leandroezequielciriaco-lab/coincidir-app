function readString(value: unknown) {
  return typeof value === 'string' && value.trim() ? value.trim() : ''
}

function normalize(value: unknown) {
  return readString(value)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
}

function readTags(value: unknown) {
  if (!Array.isArray(value)) return ''
  return value.map(readString).filter(Boolean).join(' ')
}

function getRemoteImage(data: Record<string, unknown>) {
  const candidates = [
    data.imageUrl,
    data.photoUrl,
    data.photoURL,
    data.coverImage,
    data.coverUrl,
    data.coverURL,
    data.image,
    data.imageUri,
    data.imageURL,
    data.thumbnailUrl,
  ]

  const uri = candidates.map(readString).find((value) => /^https?:\/\//i.test(value))
  return uri ? { uri } : null
}

type ImageRule = {
  image: ImageSourcePropType | ImageSourcePropType[]
  terms: string[]
}

function getStableImageKey(data: Record<string, unknown>) {
  return [
    data.activityId,
    data.id,
    data.title,
    data.name,
    data.subcategory,
    data.category,
    data.categoryId,
  ].map(readString).find(Boolean) ?? ''
}

function getStableIndex(value: string, length: number) {
  if (length <= 1) return 0

  let hash = 0
  for (let index = 0; index < value.length; index += 1) {
    hash = ((hash * 31) + value.charCodeAt(index)) >>> 0
  }

  return hash % length
}

function pickStableImage(
  image: ImageSourcePropType | ImageSourcePropType[],
  data: Record<string, unknown>,
): ImageSourcePropType | null {
  if (!Array.isArray(image)) return image as ImageSourcePropType
  if (image.length === 0) return null

  const key = getStableImageKey(data)
  const index = getStableIndex(key, image.length)

  return image[index] as ImageSourcePropType
}

